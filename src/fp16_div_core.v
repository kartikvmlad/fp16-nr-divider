/*
 * FP16 (IEEE 754 binary16) divider: Newton-Raphson reciprocal + exact-remainder rounding.
 * Round-to-nearest-even, full subnormal support, all five IEEE flags.
 * Bit-exact with model/fp16_div_model.py (see that file for the arithmetic).
 *
 * One time-shared multiply-accumulate engine, K bits of the scanned operand per clock
 * (K = 4: a divide takes 11 clocks, all operands normal). Four multiplies:
 *
 *   P2  Q0 = (N * Y0) >> 4                       N = dividend mantissa, scaled into [mb, 2*mb)
 *   P1  e  = (2^17 - mb*Y0) >> 4  (8 bits)       residual of the seed (preload 4095 turns ~x into 2^17 - x)
 *   P3  dQ = ((Q0 >> 4) * e) >> 9                signed digit on the last step: the one NR / Goldschmidt step
 *   P4  mb * Q1 + bias                           exact remainder R = N*2^11 - Q1*mb, Q1 = (Q0 + dQ) >> 2
 *
 * Q1 is Q or Q - 1 (proved for every mantissa pair by model/verify_mantissa.py), so one compare
 * of R against mb picks Q. The bias preloaded into the accumulator makes the upper product bits
 * of P4 equal N >> 1 exactly when Q1 was a legal estimate: that is the built-in remainder check.
 *
 * Registers: MA, MB (normalised mantissas), ER (exponent), QR (Q0, then Q1), H (accumulator),
 * L (scanned operand / low product bits, and finally the packed result: no result register).
 *
 * a and b must be held stable while busy is high (the wrapper guarantees it).
 */
`default_nettype none

// ------------------------------------------------------------------------------------------
// Seed ROM: Y0 = {1, seed} ~ 2^17 / mb for the 64 intervals of mb[9:4] (7-bit Y0, 64 .. 127).
// Generated by model/gen_rom.py.
// ------------------------------------------------------------------------------------------
module fp16_seed_rom (
    input  wire [5:0] idx,
    output wire [6:0] y0
);
    reg [5:0] seed;
    always @(*) begin
        case (idx)
            6'd0: seed = 6'd63; 6'd1: seed = 6'd61; 6'd2: seed = 6'd59; 6'd3: seed = 6'd57;
            6'd4: seed = 6'd56; 6'd5: seed = 6'd54; 6'd6: seed = 6'd52; 6'd7: seed = 6'd51;
            6'd8: seed = 6'd49; 6'd9: seed = 6'd47; 6'd10: seed = 6'd46; 6'd11: seed = 6'd45;
            6'd12: seed = 6'd43; 6'd13: seed = 6'd42; 6'd14: seed = 6'd40; 6'd15: seed = 6'd39;
            6'd16: seed = 6'd38; 6'd17: seed = 6'd37; 6'd18: seed = 6'd35; 6'd19: seed = 6'd34;
            6'd20: seed = 6'd33; 6'd21: seed = 6'd32; 6'd22: seed = 6'd31; 6'd23: seed = 6'd30;
            6'd24: seed = 6'd29; 6'd25: seed = 6'd28; 6'd26: seed = 6'd27; 6'd27: seed = 6'd26;
            6'd28: seed = 6'd25; 6'd29: seed = 6'd24; 6'd30: seed = 6'd23; 6'd31: seed = 6'd22;
            6'd32: seed = 6'd21; 6'd33: seed = 6'd20; 6'd34: seed = 6'd19; 6'd35: seed = 6'd18;
            6'd36: seed = 6'd18; 6'd37: seed = 6'd17; 6'd38: seed = 6'd16; 6'd39: seed = 6'd15;
            6'd40: seed = 6'd14; 6'd41: seed = 6'd14; 6'd42: seed = 6'd13; 6'd43: seed = 6'd12;
            6'd44: seed = 6'd12; 6'd45: seed = 6'd11; 6'd46: seed = 6'd10; 6'd47: seed = 6'd9;
            6'd48: seed = 6'd9; 6'd49: seed = 6'd8; 6'd50: seed = 6'd8; 6'd51: seed = 6'd7;
            6'd52: seed = 6'd6; 6'd53: seed = 6'd6; 6'd54: seed = 6'd5; 6'd55: seed = 6'd5;
            6'd56: seed = 6'd4; 6'd57: seed = 6'd3; 6'd58: seed = 6'd3; 6'd59: seed = 6'd2;
            6'd60: seed = 6'd2; 6'd61: seed = 6'd1; 6'd62: seed = 6'd1; default: seed = 6'd0;
        endcase
    end
    assign y0 = {1'b1, seed};
endmodule

// ------------------------------------------------------------------------------------------
// One multiply-accumulate step: sum = H + M * digit  (digit unsigned, or signed when `sgn`
// is set and its top bit is 1). H is signed; sum is 13 + K bits.
// ------------------------------------------------------------------------------------------
module fp16_mac #(
    parameter K = 4
) (
    input  wire signed [12:0]   h,
    input  wire        [11:0]   m,
    input  wire        [K-1:0]  dig,
    input  wire                 sgn,        // top digit bit has weight -2^(K-1) (last step of the signed operand)
    output wire signed [12:0]   nxt_h,      // sum >>> K
    output wire        [K-1:0]  sum_lo
);
    localparam SW = 13 + K;
    wire                 t    = dig[K-1];
    wire        [SW-1:0] mt   = {{(SW-12-(K-1)){1'b0}}, m, {(K-1){1'b0}}} & {SW{t}};   // top row: m << (K-1)
    wire        [SW-1:0] row  = mt ^ {SW{t & sgn}};                                      // ... or its one's complement
    wire        [SW-1:0] pp   = m * dig[K-2:0];
    wire        [SW-1:0] hx   = {{(SW-13){h[12]}}, h};
    wire        [SW-1:0] sum  = hx + pp + row + {{(SW-1){1'b0}}, t & sgn};
    wire signed [SW-1:0] sum_s = sum;
    assign nxt_h  = sum_s >>> K;
    assign sum_lo = sum[K-1:0];
endmodule

// ------------------------------------------------------------------------------------------
// out == in or in + 1 ?  x = out ^ in must be a run of ones starting at bit 0 (or zero) and its
// bit 0 must equal the increment that was applied.
// ------------------------------------------------------------------------------------------
module fp16_incchk #(
    parameter W = 10
) (
    input  wire [W-1:0] i,
    input  wire [W-1:0] o,
    input  wire         inc,
    output wire         ok
);
    wire [W-1:0] x = o ^ i;
    assign ok = (x[0] == inc) & (&(~x[W-1:1] | x[W-2:0]));
endmodule

// ------------------------------------------------------------------------------------------
// Remainder: R = ~(low 12 product bits), compare with mb, corrected quotient, built-in check.
// ------------------------------------------------------------------------------------------
module fp16_rem #(
    parameter PW = 13               // width of prod_hi
) (
    input  wire [11:0] prod_lo,     // low 12 bits of the biased P4 product
    input  wire [PW-1:0] prod_hi,   // product >> 12
    input  wire [10:0] ma,
    input  wire [10:0] mb,
    input  wire        ge,          // ma >= mb
    input  wire [11:0] q1,          // the estimate
    output wire [11:0] q,           // corrected quotient
    output wire        rem_nz,
    output wire        ge2_o,
    output wire        chk_ok
);
    wire [11:0] r      = ~prod_lo;
    wire        hi_ok  = (prod_hi == {{(PW-11){1'b0}}, (ge ? {1'b0, ma[10:1]} : ma)});
    wire        ge2    = (r >= {1'b0, mb});
    wire        big    = (r >= {mb, 1'b0});
    wire        eq_mb  = (r == {1'b0, mb});
    assign ge2_o  = ge2;
    assign rem_nz = ge2 ? ~eq_mb : (r != 12'd0);
    assign q      = q1 + {11'd0, ge2};
`ifdef FP16_NO_CHK_REM
    assign chk_ok = 1'b1;                     // ablation build: remainder check disabled
`else
    assign chk_ok = hi_ok & ~big;
`endif
endmodule

// ------------------------------------------------------------------------------------------
// Rounder / packer. One result word for every outcome:
//   normal (FIN)      {s, exponent, fraction}, overflow -> infinity
//   subnormal (RND)   {s, 0000, keep[10:0]}  (a rounding carry lands in the exponent field)
//   f_inf / f_nan / f_zero   special results and the flush to zero of a deep underflow
// ------------------------------------------------------------------------------------------
module fp16_round (
    input  wire        s,
    input  wire [11:0] qv,          // 12-bit quotient: 11 kept bits + round bit
    input  wire        stkv,        // sticky
    input  wire signed [6:0] e,     // result exponent before rounding
    input  wire        m_sub,       // pack as a subnormal result
    input  wire        f_nan,
    input  wire        f_inf,
    input  wire        f_zero,
    output wire        carry,       // rounding carried out of the 11 kept bits
    output wire        ovf,         // normal result overflows to infinity
    output wire        inexact,
    output wire [15:0] res,
    output wire [10:0] keep_o,
    output wire        inc_o,
    output wire        plain_o      // plain normal result (not special, not subnormal, not overflow)
);
    wire [10:0] keep    = qv[11:1];
    wire        rnd     = qv[0];
    wire        inc     = rnd & (stkv | keep[0]);
    wire [11:0] keepr   = {1'b0, keep} + {11'd0, inc};
    assign inexact = rnd | stkv;
    assign carry   = keepr[11];

    wire signed [6:0] er = e + $signed({6'd0, keepr[11]});
    assign ovf = ~er[6] & (er[5] | (&er[4:0]));
    wire   nrm  = ~(f_nan | f_inf | f_zero | m_sub);          // plain normal result
    wire   n_ovf = ovf & nrm;
    wire   all1 = f_nan | f_inf | n_ovf;
    wire [4:0] ex = all1 ? 5'h1F : m_sub ? {4'b0000, keepr[10]} : f_zero ? 5'd0 : er[4:0];
    wire [9:0] fr = f_nan ? 10'h200 : (f_inf | f_zero | n_ovf) ? 10'd0 : keepr[9:0];
    assign res = {s & ~f_nan, ex, fr};
    assign keep_o  = keep;
    assign inc_o   = inc;
    assign plain_o = nrm & ~ovf;
endmodule

// ------------------------------------------------------------------------------------------
// Operand decode: special cases, the result for them, and the starting exponent.
// ------------------------------------------------------------------------------------------
module fp16_spec (
    input  wire [15:0] a,
    input  wire [15:0] b,
    output wire        special_n,
    output wire        invalid_n,
    output wire        divz_n,
    output wire        nan_n,
    output wire        inf_n,
    output wire        a_sub,
    output wire        b_sub,
    output wire        s,
    output wire        a_e0,
    output wire        b_e0,
    output wire signed [6:0] er_init
);
    wire        sa = a[15], sb = b[15];
    wire [4:0]  ea = a[14:10], eb = b[14:10];
    wire [9:0]  fa = a[9:0],   fb = b[9:0];
    wire a_fz   = (fa == 10'd0);
    wire b_fz   = (fb == 10'd0);
    assign a_e0 = (ea == 5'd0);
    assign b_e0 = (eb == 5'd0);
    wire a_zero = a_e0 && a_fz;
    wire b_zero = b_e0 && b_fz;
    assign a_sub = a_e0 && !a_fz;
    assign b_sub = b_e0 && !b_fz;
    wire a_inf  = (ea == 5'd31) && a_fz;
    wire b_inf  = (eb == 5'd31) && b_fz;
    wire a_nan  = (ea == 5'd31) && !a_fz;
    wire b_nan  = (eb == 5'd31) && !b_fz;
    wire a_snan = a_nan && !fa[9];
    wire b_snan = b_nan && !fb[9];

    assign invalid_n = (a_zero && b_zero) || (a_inf && b_inf) || a_snan || b_snan;
    assign nan_n   = a_nan || b_nan || invalid_n;
    assign divz_n = b_zero && !a_zero && !a_inf && !a_nan;
    assign inf_n   = (a_inf && !b_inf && !b_nan) || divz_n;
    wire zero_n    = (a_zero && !b_zero && !b_nan && !a_nan) || (b_inf && !a_inf && !a_nan);
    assign special_n = nan_n || inf_n || zero_n;
    assign s = sa ^ sb;

    // exponent before normalisation: Ea - Eb + 15, subnormals counted as exponent 1
    wire [4:0]  ea_e = {ea[4:1], ea[0] | a_e0};
    wire [4:0]  eb_e = {eb[4:1], eb[0] | b_e0};
    assign er_init = $signed({2'b00, ea_e}) - $signed({2'b00, eb_e}) + 7'sd15;

endmodule

// ------------------------------------------------------------------------------------------
`ifndef FP16_K
`define FP16_K 2             // multiplier digit width (2 .. 12); override with -DFP16_K=n
`endif
module fp16_div_core #(
    parameter K = `FP16_K
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        start,
    input  wire [15:0] a,
    input  wire [15:0] b,
    output wire [15:0] result,       // valid from done until the next start
    output reg  [4:0]  flags,        // {invalid, divzero, overflow, underflow, inexact}
    output reg         fault,        // self-check failed on the last divide
    output reg         corrected,    // a fault was detected and the retry delivered the result
    output wire        busy,
    output reg         done
);

    localparam S1  = (7 + K - 1) / K;      // steps to scan Y0 (7 bits)
    localparam S3  = (8 + K - 1) / K;      // steps to scan e (8 bits, signed)
    localparam S4  = (11 + K - 1) / K;     // steps to scan mb (11 bits)
    localparam SK1 = S1 * K;
    localparam SK3 = S3 * K;
    localparam SK4 = S4 * K;
    localparam W1  = 13 + SK1;
    localparam W3  = 13 + SK3;
    localparam W4  = 13 + SK4;

    localparam [2:0] PH_NORM = 3'd0,       // shift subnormal mantissas left, one bit per clock
                     PH_P2   = 3'd1,
                     PH_P1   = 3'd2,
                     PH_P3   = 3'd3,
                     PH_P4   = 3'd4,
                     PH_FIN  = 3'd5,       // remainder compare, round, pack
                     PH_DEN  = 3'd6,       // shift a subnormal result right, one bit per clock
                     PH_RND  = 3'd7;       // round and pack a subnormal result

    reg        run;
    reg  [2:0] ph;
    reg  [2:0] cnt;                        // steps left in this phase
    reg        rty;                        // the divide has been repeated once already
    reg        wd_act;                     // watchdog armed: a divide is expected to finish
    reg  [5:0] wd;                         // watchdog LFSR (x^6 + x^5 + 1), restarted at every go
    reg        re_go;                      // one-clock pulse: restart after a detected fault
    assign busy = run | re_go;             // stays high across the restart so the wrapper cannot write
    wire       go = start | re_go;

    // ---------------- operand decode ----------------
    wire        special_n, invalid_n, divz_n, nan_n, inf_n, a_sub, b_sub, s, a_e0, b_e0;
    wire signed [6:0] er_init;
    fp16_spec u_spec (.a(a), .b(b), .special_n(special_n), .invalid_n(invalid_n), .divz_n(divz_n),
                      .nan_n(nan_n), .inf_n(inf_n), .a_sub(a_sub), .b_sub(b_sub), .s(s), .a_e0(a_e0), .b_e0(b_e0),
                      .er_init(er_init));
    wire [9:0] fa = a[9:0], fb = b[9:0];

    // ---------------- working registers ----------------
    reg        [10:0] MA, MB;     // normalised mantissas, hidden bit at [10]
    reg signed [6:0]  ER;         // ea - eb + 15 (+ normalisation shifts)
    reg        [14:0] QR;         // Q0 (15 bits: the estimate can slightly exceed 2^14), then Q1
    reg signed [12:0] H;          // accumulator
    reg        [15:0] L;          // scanned operand / low product bits / result
    reg               rem_r;      // sticky of the subnormal result path
    reg               tiny_r;     // result is tiny after rounding
    reg               spec_r;     // special-case operands: pack the special result
    assign result = L;

    wire        ge   = (MA >= MB);
    wire [11:0] N    = ge ? {1'b0, MA} : {MA, 1'b0};
    wire        N0   = ge & MA[0];

    // ---------------- seed ROM (index: the next MB while normalising, else MB; at start the raw b) ----------------
    wire        norm_ph = run && (ph == PH_NORM);
    wire [5:0]  rom_idx = !run ? b[9:4] : (norm_ph & ~MB[10]) ? MB[8:3] : MB[9:4];
    wire [6:0]  y0_raw;
    fp16_seed_rom u_rom (.idx(rom_idx), .y0(y0_raw));

    // ---------------- multiply-accumulate engine ----------------
    wire [11:0] Msel_raw = (ph == PH_P2) ? N : (ph == PH_P3) ? {1'b0, QR[14:4]} :
                           (ph == PH_P4) ? QR[11:0] : {1'b0, MB};
    wire [K-1:0] dig = L[K-1:0];
    wire        last = (cnt == 3'd0);
    wire        sgnm = (ph == PH_P3) && last;                  // signed top digit of e
    wire signed [12:0] nxtH_raw;
    wire [K-1:0]       sum_lo_raw;
    wire signed [12:0] nxtH;
    wire [K-1:0]       sum_lo;
    wire [11:0]        Msel;
    fp16_mac #(.K(K)) u_mac (.h(H), .m(Msel), .dig(dig), .sgn(sgnm), .nxt_h(nxtH_raw), .sum_lo(sum_lo_raw));
    wire        [15:0]   nxtL = {sum_lo, L[15:K]};

    // values handed from one phase to the next (valid on the last step of a phase)
    wire        [W1-1:0] full1 = {nxtH, nxtL[15:16-SK1]};
    wire        [14:0]   q0    = full1[18:4];                  // P2
    wire        [7:0]    e_t   = ~full1[11:4];                 // P1
    wire signed [W3-1:0] full3 = {nxtH, nxtL[15:16-SK3]};      // P3
    wire signed [W3-1:0] dqf   = full3 >>> 9;
    wire signed [15:0]   q1f   = $signed({1'b0, QR}) + $signed(dqf[9:0]);
    wire        [11:0]   q1    = q1f[13:2];

    // ---------------- FIN: remainder, compare, round ----------------
    wire [W4-1:0] full4  = {H, L[15:16-SK4]};
    wire [11:0]   Qf_raw;
    wire [11:0]   Qf;
    wire          rem_nz, chk_ok, ge2_s;
    fp16_rem #(.PW(W4-12)) u_rem (.prod_lo(full4[11:0]), .prod_hi(full4[W4-1:12]), .ma(MA), .mb(MB), .ge(ge),
                    .q1(QR[11:0]), .q(Qf_raw), .rem_nz(rem_nz), .ge2_o(ge2_s), .chk_ok(chk_ok));

    wire signed [6:0] E  = ER - {6'd0, ~ge};

    wire [11:0]   qv     = (ph == PH_FIN) ? Qf : L[11:0];
    wire          stkv   = (ph == PH_FIN) ? rem_nz : rem_r;
    wire          carry, ovf, inexact, plain_o, inc_o;
    wire [10:0]   keep_o;
    wire [15:0]   res_raw;
    wire [15:0]   res;
    wire          in_fin = (ph == PH_FIN);
`ifdef FP16_NO_CHK_ER
    wire          er_ok  = 1'b1;                                          // ablation build
`else
    wire          er_ok  = a_sub | b_sub | (ER == er_init);               // ER still at its start value
`endif
`ifdef FP16_NO_CHK_SRC
    wire          src_ok = 1'b1;                                          // ablation build
`else
    wire          src_ok = (b_sub | (MB == {1'b1, fb})) & (a_sub | (MA == {1'b1, fa}));   // MA, MB still equal the operands
`endif
`ifdef FP16_NO_RETRY
    wire          can_retry = 1'b0;                                       // ablation build: detect only
`else
    wire          can_retry = ~rty;
`endif
    wire          e_pos  = ~E[6] & (E != 7'sd0);                 // E >= 1
    wire          e_far  = E[6] & (E < -7'sd10);                 // E <= -11: everything shifts out
`ifdef FP16_NO_CHK_PACK
    wire          pk_ok  = 1'b1;
    wire          sb_ok  = 1'b1;
`else
    wire q_ok, f_ok, x_ok, s_ok;
    fp16_incchk #(.W(12)) u_cq (.i(QR[11:0]), .o(Qf), .inc(ge2_s), .ok(q_ok));
    fp16_incchk #(.W(10)) u_cf (.i(keep_o[9:0]), .o(res[9:0]), .inc(inc_o), .ok(f_ok));
    fp16_incchk #(.W(5))  u_ce (.i(E[4:0]), .o(res[14:10]), .inc(carry), .ok(x_ok));
    fp16_incchk #(.W(11)) u_cs (.i(keep_o), .o(res[10:0]), .inc(inc_o), .ok(s_ok));
    // FIN: Qf from Q1, and, when the plain result is used, its fraction / exponent / sign
    wire          pk_ok  = q_ok & (~(e_pos & plain_o) | (f_ok & x_ok & (res[15] == s)));
    // RND: the subnormal result
    wire          sb_ok  = s_ok & (res[14:11] == 4'd0) & (res[15] == s);
`endif
    wire          reg_ok = er_ok & src_ok & pk_ok;
    wire          det    = ~(chk_ok & reg_ok) & ~spec_r;                    // a fault was detected
    fp16_round u_round (.s(s), .qv(qv), .stkv(stkv), .e(E), .m_sub(ph == PH_RND),
                        .f_nan(in_fin & spec_r & nan_n), .f_inf(in_fin & spec_r & inf_n),
                        .f_zero(in_fin & (spec_r ? ~(nan_n | inf_n) : e_far)),
                        .carry(carry), .ovf(ovf), .inexact(inexact), .res(res_raw),
                        .keep_o(keep_o), .inc_o(inc_o), .plain_o(plain_o));


    // ---------------- fault-injection taps (simulation only) ----------------
    // Each tap is ((in ^ x) | s) & ~c with masks driven by test/tb_fault.v; without FAULT_INJECT
    // the nets pass straight through and nothing is synthesised.
`ifdef FAULT_INJECT
    reg [31:0] fi_y0_x = 0, fi_y0_s = 0, fi_y0_c = 0;
    reg [31:0] fi_m_x = 0,  fi_m_s = 0,  fi_m_c = 0;
    reg [31:0] fi_h_x = 0,  fi_h_s = 0,  fi_h_c = 0;
    reg [31:0] fi_l_x = 0,  fi_l_s = 0,  fi_l_c = 0;
    reg [31:0] fi_q_x = 0,  fi_q_s = 0,  fi_q_c = 0;
    reg [31:0] fi_r_x = 0,  fi_r_s = 0,  fi_r_c = 0;
    wire [6:0]  y0      = ((y0_raw ^ fi_y0_x[6:0]) | fi_y0_s[6:0]) & ~fi_y0_c[6:0];
    assign Msel         = ((Msel_raw ^ fi_m_x[11:0]) | fi_m_s[11:0]) & ~fi_m_c[11:0];
    assign nxtH         = ((nxtH_raw ^ fi_h_x[12:0]) | fi_h_s[12:0]) & ~fi_h_c[12:0];
    assign sum_lo       = ((sum_lo_raw ^ fi_l_x[K-1:0]) | fi_l_s[K-1:0]) & ~fi_l_c[K-1:0];
    assign Qf           = ((Qf_raw ^ fi_q_x[11:0]) | fi_q_s[11:0]) & ~fi_q_c[11:0];
    assign res          = ((res_raw ^ fi_r_x[15:0]) | fi_r_s[15:0]) & ~fi_r_c[15:0];
`else
    wire [6:0]  y0      = y0_raw;
    assign Msel         = Msel_raw;
    assign nxtH         = nxtH_raw;
    assign sum_lo       = sum_lo_raw;
    assign Qf           = Qf_raw;
    assign res          = res_raw;
`endif

    // ---------------- datapath ----------------
    always @(posedge clk) begin
        if (!run) begin
            MA <= {~a_e0, fa};
            MB <= {~b_e0, fb};
            ER <= er_init;
            H  <= 13'sd0;
            if (go)                                          // L holds the last result until then
                L <= {9'd0, y0};
        end else begin
            case (ph)
                PH_NORM: begin
                    if (~MA[10]) MA <= {MA[9:0], 1'b0};
                    if (~MB[10]) MB <= {MB[9:0], 1'b0};
                    ER <= ER + {6'd0, ~MB[10]} - {6'd0, ~MA[10]};
                    L  <= {9'd0, y0};
                    H  <= 13'sd0;
                end
                PH_P2, PH_P1, PH_P3, PH_P4: begin
                    H <= nxtH;
                    L <= nxtL;
                    if (last) begin
                        case (ph)
                            PH_P2: begin
                                QR <= q0;
                                H  <= 13'sd4095;
                                L  <= {9'd0, y0};
                            end
                            PH_P1: begin
                                L <= {{8{e_t[7]}}, e_t};
                                H <= 13'sd0;
                            end
                            PH_P3: begin
                                QR <= {3'b000, q1};
                                L  <= {5'd0, MB};
                                H  <= {1'b0, ~N0, 11'h7FF};
                            end
                            default: ;
                        endcase
                    end
                end
                PH_FIN: begin
                    if (spec_r | e_pos | e_far) L <= res;
                    else begin
                        L      <= {4'd0, Qf};
                        rem_r  <= rem_nz;
                        tiny_r <= E[6] | ~carry;
                        ER     <= E;
                    end
                end
                PH_DEN: begin
                    L     <= {1'b0, L[15:1]};
                    rem_r <= rem_r | L[0];
                    ER    <= ER + 7'sd1;
                end
                PH_RND: L <= res;
            endcase
        end
    end

    // ---------------- control ----------------
    // handshake and status flops (reset)
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            run       <= 1'b0;
            fault     <= 1'b0;
            corrected <= 1'b0;
            done      <= 1'b0;
            rty       <= 1'b0;
            re_go     <= 1'b0;
            wd_act    <= 1'b0;
        end else begin
            done  <= 1'b0;
            re_go <= 1'b0;
            if (go) wd_act <= 1'b1;
`ifndef FP16_NO_WD
            if (wd_act & (wd == 6'd31)) begin       // 56 clocks without done: give up
                fault     <= 1'b1;
                corrected <= 1'b0;
                done      <= 1'b1;
                run       <= 1'b0;
                wd_act    <= 1'b0;
            end else
`endif
            if (!run) begin
                if (go) begin
                    if (start) begin
                        fault     <= 1'b0;
                        corrected <= 1'b0;
                        rty       <= 1'b0;
                    end
                    run <= 1'b1;
                end
            end else begin
                if (ph == PH_FIN) begin
                    if (det & can_retry) begin                   // fault: repeat the divide once
                        rty   <= 1'b1;
                        re_go <= 1'b1;
                        run   <= 1'b0;
                    end else begin
                        fault     <= det;                        // the repeat failed too
                        corrected <= rty & ~det;                 // the repeat passed (rty is never set without retry)
                        if (spec_r | e_pos | e_far) begin
                            done <= 1'b1;
                            run  <= 1'b0;
                            wd_act <= 1'b0;
                        end
                    end
                end
                if (ph == PH_RND) begin
                    done <= 1'b1;
                    run  <= 1'b0;
                    if (!sb_ok) fault <= 1'b1;
                    wd_act <= 1'b0;
                end
            end
        end
    end

    always @(posedge clk) wd <= go ? 6'd1 : {wd[4:0], wd[5] ^ wd[4]};

    // phase sequencing and flags (no reset: only meaningful while run is set / after done)
    always @(posedge clk) begin
        if (!run) begin
            if (go) begin
                spec_r <= special_n;
                if (special_n) ph <= PH_FIN;
                else if (a_sub | b_sub) ph <= PH_NORM;
                else begin
                    ph  <= PH_P2;
                    cnt <= S1 - 1;
                end
            end
        end else begin
            case (ph)
                PH_NORM: begin
                    if ((MA[10] | MA[9]) & (MB[10] | MB[9])) begin
                        ph  <= PH_P2;
                        cnt <= S1 - 1;
                    end
                end
                PH_P2, PH_P1, PH_P3, PH_P4: begin
                    if (!last) cnt <= cnt - 3'd1;
                    else begin
                        case (ph)
                            PH_P2: begin ph <= PH_P1; cnt <= S1 - 1; end
                            PH_P1: begin ph <= PH_P3; cnt <= S3 - 1; end
                            PH_P3: begin ph <= PH_P4; cnt <= S4 - 1; end
                            default: ph <= PH_FIN;
                        endcase
                    end
                end
                PH_FIN: begin
                    if (!(det & can_retry)) begin
                        if (spec_r | e_pos | e_far)
                            flags <= spec_r ? {invalid_n, divz_n, 3'b000} : e_far ? 5'b00011 :
                                     ovf ? 5'b00101 : {4'b0000, inexact};
                        else
                            ph <= PH_DEN;
                    end
                end
                PH_DEN: begin
                    if (ER == 7'sd0) ph <= PH_RND;
                end
                PH_RND: flags <= {3'b000, tiny_r & inexact, inexact};
            endcase
        end
    end

endmodule
